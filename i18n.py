def get_lang(request) -> str:
    lang = request.cookies.get("lang", "en")
    return lang if lang in STRINGS else "en"


def strings(lang: str) -> dict:
    return STRINGS.get(lang, STRINGS["en"])


def other_lang(lang: str) -> str:
    return "zh" if lang == "en" else "en"


def status_label(lang: str, status: str) -> str:
    key = f"status_{status}"
    return strings(lang).get(key, status)


def type_label(lang: str, type_name: str) -> str:
    key = f"type_{type_name}"
    return strings(lang).get(key, type_name)


def role_label(lang: str, role: str) -> str:
    key = f"role_{role}"
    return strings(lang).get(key, role)


def topic_label(lang: str, topic: str) -> str:
    if lang == "zh":
        return TOPIC_ZH.get(topic, topic)
    return topic


def skill_label(lang: str, skill: str) -> str:
    cleaned = (skill or "").replace("_", " ")
    if lang == "zh":
        return SKILL_ZH.get(cleaned.lower(), cleaned)
    return cleaned


